    private void loadProducts() {
        JButton[] productBtns = {
                EmpCheckoutBtn1, EmpCheckoutBtn2, EmpCheckoutBtn3,
                EmpCheckoutBtn4, EmpCheckoutBtn5, EmpCheckoutBtn6,
                EmpCheckoutBtn7, EmpCheckoutBtn8, EmpCheckoutBtn9
        };

        List<Product> products = service.getAllEntries();

        for (JButton btn : productBtns) {
            btn.setVisible(false);
            btn.setText("");
        }

        for (int i = 0; i < products.size() && i < 9; i++) {
            Product p = products.get(i);
            final int index = i;

            productBtns[i].setText(p.getName());
            productBtns[i].setVisible(true);
            productBtns[i].setBackground(Color.WHITE);
            productBtns[i].setForeground(Color.BLACK);
            productBtns[i].setOpaque(true);

            for (ActionListener al : productBtns[i].getActionListeners()) {
                productBtns[i].removeActionListener(al);
            }

            productBtns[i].addActionListener(e -> {
                if (selectedIndexes.contains(index)) {
                    selectedIndexes.remove(index);
                    productBtns[index].setBackground(Color.WHITE);
                    productBtns[index].setForeground(Color.BLACK);
                    terminal.setCommand(new CheckoutRemoveItem(action, p));
                } else {
                    selectedIndexes.add(index);
                    productBtns[index].setBackground(new Color(0, 153, 153));
                    productBtns[index].setForeground(Color.WHITE);
                    terminal.setCommand(new CheckoutAddItem(action, p));
                }

                terminal.executeCommand(); // ← actually fire the command
                refreshCart();             // ← update the display after every press
            });
        }

        refreshCart(); // initial display (will be empty, which is correct)
    }

    private void refreshCart() {
        List<Product> cartItems = action.getCart();
        String productNames = "";
        double totalPrice = 0;

        for (Product item : cartItems) {
            productNames += item.getName() + ", "; // += actually updates the string
            totalPrice += item.getPrice();
        }

        // trim trailing ", " if cart isn't empty
        if (!productNames.isEmpty()) {
            productNames = productNames.substring(0, productNames.length() - 2);
        }

        EmpCheckoutNameField.setText(productNames);
        EmpCheckoutPriceField.setText("₱" + String.format("%.2f", totalPrice));
    }


